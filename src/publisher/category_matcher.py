def detect_gender_profile(title: str, categories: list[str]) -> str:
    """
    Определяет гендерную направленность товара ('men', 'women', 'kids', 'unknown')
    по названию и оригинальным категориям.
    """
    text = (str(title) + " " + " ".join(str(c) for c in categories)).lower()

    # Дети имеют высший приоритет (детская одежда для мальчика/девочки)
    if any(k in text for k in ["дитяч", "діт", "детск", "детям", "kids", "хлопчик", "дівчат", "мальчик", "девочк"]):
        return "kids"
    if any(k in text for k in ["чоловіч", "чоловік", "мужск", "мужчин", "men", "man"]):
        return "men"
    if any(k in text for k in ["жіноч", "жінк", "женск", "женщин", "women", "woman"]):
        return "women"
    return "unknown"


def get_category_synonyms(cat_name: str) -> set[str]:
    """Возвращает набор форм и синонимов для имени категории."""
    clean = str(cat_name).strip().lower()
    synonyms = {clean}

    # Ищем прямое совпадение в словаре
    if clean in CATEGORY_SYNONYMS:
        synonyms.update(s.lower() for s in CATEGORY_SYNONYMS[clean])

    # Ищем совпадения по частям фразы (например 'Сорочки та теніски')
    for k, syn_list in CATEGORY_SYNONYMS.items():
        if k in clean or clean in k:
            synonyms.update(s.lower() for s in syn_list)

    # Проверяем корневые категории
    if clean in ROOT_CATEGORY_MAPPINGS:
        synonyms.add(ROOT_CATEGORY_MAPPINGS[clean])
    for uk, ru in ROOT_CATEGORY_MAPPINGS.items():
        if clean == ru:
            synonyms.add(uk)

    return synonyms


def score_category_candidate(btn_title: str, btn_path: str, target_categories: list[str], gender: str) -> float:
    """
    Оценивает релевантность кнопки категории.
    Возвращает числовой балл. Если балл < 0 — кандидат не подходит (несовместимый гендер).
    """
    title_clean = str(btn_title).strip().lower()
    path_clean = str(btn_path).strip().lower()
    combined = f"{title_clean} {path_clean}"

    # 1. Проверка гендера / раздела по хлебным крошкам
    if gender == "men":
        # Если товар строго мужской, исключаем женские и детские разделы
        forbidden_men = ["женск", "жіноч", "детск", "дитяч", "беременных", "вагітних", "дівчат", "девоч"]
        if any(w in combined for w in forbidden_men):
            return -100.0
    elif gender == "women":
        forbidden_women = ["мужск", "чоловіч", "детск", "дитяч", "хлопчик", "мальчик"]
        if any(w in combined for w in forbidden_women):
            return -100.0
    elif gender == "kids":
        # Для детских вещей разделы только для взрослых не подходят
        if not any(w in combined for w in ["детск", "дитяч", "kids", "діт", "мальчик", "девоч", "хлопчик", "дівчат"]):
            if any(w in combined for w in ["мужск", "чоловіч", "женск", "жіноч"]):
                return -50.0

    score = 0.0

    # Бонус за прямое указание гендера в пути
    if gender == "men" and any(w in path_clean for w in ["мужск", "чоловіч", "men"]):
        score += 40.0
    elif gender == "women" and any(w in path_clean for w in ["женск", "жіноч", "women"]):
        score += 40.0
    elif gender == "kids" and any(w in path_clean for w in ["детск", "дитяч", "kids", "діт"]):
        score += 40.0

    # 2. Сопоставление целевых категорий
    if not target_categories:
        return score

    leaf_cat = target_categories[0]
    leaf_synonyms = get_category_synonyms(leaf_cat)

    # 2.1 Проверка соответствия заголовка кнопки (листовой категории)
    if title_clean in leaf_synonyms:
        score += 100.0
    elif any(s in title_clean or title_clean in s for s in leaf_synonyms if len(s) >= 4):
        score += 80.0

    # 2.2 Проверка наличия целевых категорий в полном пути (хлебных крошках)
    for cat in target_categories:
        cat_synonyms = get_category_synonyms(cat)
        matched = False
        for syn in cat_synonyms:
            if syn in path_clean:
                score += 30.0
                matched = True
                break
            elif any(part.strip() in path_clean for part in syn.split() if len(part.strip()) >= 5):
                score += 15.0
                matched = True
                break
        if matched and cat == leaf_cat:
            score += 20.0

    return score
